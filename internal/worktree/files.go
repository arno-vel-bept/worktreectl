var envKey = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`)
var projectChars = regexp.MustCompile(`[^a-z0-9_-]`)

func readEnv(path string) (map[string]string, error) {
	values := map[string]string{}
	f, err := os.Open(filepath.Join(path, ".worktree.env"))
	if os.IsNotExist(err) {
		return values, nil
	}
	if err != nil {
		return nil, err
	}
	defer f.Close()
	scanner := bufio.NewScanner(f)
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		key, raw, ok := strings.Cut(strings.TrimPrefix(line, "export "), "=")
		if !ok || !envKey.MatchString(key) {
			return nil, fmt.Errorf("invalid environment entry in %s/.worktree.env", path)
		}
		value, err := shellValue(raw)
		if err != nil {
			return nil, fmt.Errorf("%s/.worktree.env: %s: %w", path, key, err)
		}
		values[key] = value
	}
	return values, scanner.Err()
}

// Decode literal shell quoting (including the prototype's backslash escaping),
// never source/evaluate a file. Command substitutions cannot run here.
func shellValue(raw string) (string, error) {
	var b strings.Builder
	quote := byte(0)
	for i := 0; i < len(raw); i++ {
		c := raw[i]
		if quote == '\'' {
			if c == '\'' {
				quote = 0
			} else {
				b.WriteByte(c)
			}
			continue
		}
		if c == '\\' {
			i++
			if i == len(raw) {
				return "", fmt.Errorf("trailing backslash")
			}
			b.WriteByte(raw[i])
		} else if c == quote && quote != 0 {
			quote = 0
		} else if quote == 0 && (c == '\'' || c == '"') {
			quote = c
		} else if c == '$' || c == '`' || (quote == 0 && strings.ContainsRune(" ;&|<>()\t", rune(c))) {
			return "", fmt.Errorf("unsupported shell expression; use single-quoted literal values")
		} else {
			b.WriteByte(c)
		}
	}
	if quote != 0 {
		return "", fmt.Errorf("unterminated quote")
	}
	return b.String(), nil
}

func quoteValue(value string) string { return "'" + strings.ReplaceAll(value, "'", "'\\''") + "'" }

func environment(path string) ([]string, error) {
	values, err := readEnv(path)
	if err != nil {
		return nil, err
	}
	for _, entry := range os.Environ() {
		key, value, _ := strings.Cut(entry, "=")
		if _, exists := values[key]; !exists {
			values[key] = value
		}
	}
	result := make([]string, 0, len(values))
	for key, value := range values {
		result = append(result, key+"="+value)
	}
	sort.Strings(result)
	return result, nil
}

func (s *Service) writeEnv(path, name, branch string, port int) error {
	values := map[string]string{
		"WORKTREE_NAME": name, "WORKTREE_PATH": path, "WORKTREE_MAIN": s.Repo.Main,
		"WORKTREE_BRANCH": branch, "WORKTREE_PORT": strconv.Itoa(port), "PORT": strconv.Itoa(port),
		"COMPOSE_PROJECT_NAME": projectChars.ReplaceAllString(strings.ToLower(filepath.Base(s.Repo.Main)+"-"+name), "-"),
	}
	keys := []string{"WORKTREE_NAME", "WORKTREE_PATH", "WORKTREE_MAIN", "WORKTREE_BRANCH", "WORKTREE_PORT", "PORT", "COMPOSE_PROJECT_NAME"}
	var data strings.Builder
	data.WriteString("# generated by worktreectl; load with: set -a; . ./.worktree.env; set +a\n")
	for _, key := range keys {
		fmt.Fprintf(&data, "%s=%s\n", key, quoteValue(values[key]))
	}
	// Exclusive creation prevents following an unexpected symlink from a commit.
	f, err := os.OpenFile(filepath.Join(path, ".worktree.env"), os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0600)
	if err != nil {
		return err
	}
	_, writeErr := io.WriteString(f, data.String())
	closeErr := f.Close()
	if writeErr != nil {
		return writeErr
	}
	return closeErr
}

func (s *Service) pickPort(ctx context.Context, name string) (int, error) {
	taken := map[int]bool{}
	trees, err := s.Repo.Trees(ctx)
	if err != nil {
		return 0, err
	}
	for _, w := range trees {
		values, err := readEnv(w.Path)
		if err != nil {
			return 0, err
		}
		port, _ := strconv.Atoi(values["WORKTREE_PORT"])
		taken[port] = true
	}
	slots := min(600, (65535-s.Config.PortBase)/10+1)
	start := int(crc32.ChecksumIEEE([]byte(s.Repo.Main+"/"+name))) % min(500, slots)
	for i := 0; i < slots; i++ {
		port := s.Config.PortBase + ((start+i)%slots)*10
		if taken[port] {
			continue
		}
		listener, err := net.Listen("tcp", fmt.Sprintf("127.0.0.1:%d", port))
		if err == nil {
			listener.Close()
			return port, nil
		}
	}
	return 0, fmt.Errorf("no free worktree port in configured range")
}

func (s *Service) copyIncludes(dst string) error {
	patterns := s.Config.Copy
	if patterns == nil {
		data, err := os.ReadFile(filepath.Join(s.Repo.Main, ".worktreeinclude"))
		if err != nil && !os.IsNotExist(err) {
			return err
		}
		if os.IsNotExist(err) {
			patterns = []string{".env", ".env.*"}
		} else {
			patterns = strings.Split(string(data), "\n")
		}
	}
	for _, pattern := range patterns {
		pattern, _, _ = strings.Cut(pattern, "#")
		pattern = strings.TrimSpace(pattern)
		if pattern == "" || strings.HasPrefix(pattern, "!") {
			continue
		}
		pattern = strings.TrimSuffix(strings.TrimPrefix(pattern, "/"), "/")
		if unsafeRelative(pattern) {
			return fmt.Errorf("unsafe copy pattern %q: paths must stay inside the checkout", pattern)
		}
		matches, err := filepath.Glob(filepath.Join(s.Repo.Main, pattern))
		if err != nil {
			return err
		}
		for _, src := range matches {
			rel, _ := filepath.Rel(s.Repo.Main, src)
			if err := copyEntry(src, filepath.Join(dst, rel), s.Repo.Main, dst); err != nil {
				return fmt.Errorf("copy %s: %w", rel, err)
			}
		}
	}
	return nil
}

func unsafeRelative(path string) bool {
	if filepath.IsAbs(path) {
		return true
	}
	for _, part := range strings.Split(filepath.ToSlash(path), "/") {
		if part == ".." || part == ".git" || part == ".worktree.env" {
			return true
		}
	}
	return false
}

func copyEntry(src, dst, sourceRoot, destRoot string) error {
	if filepath.Base(src) == ".git" || filepath.Base(src) == ".worktree.env" {
		return nil
	}
	if !repo.Under(filepath.Dir(src), sourceRoot) || !repo.Under(filepath.Dir(dst), destRoot) {
		return fmt.Errorf("copy would traverse a symlink outside the checkout")
	}
	info, err := os.Lstat(src)
	if err != nil {
		return err
	}
	if _, err := os.Lstat(dst); err == nil {
		return nil // Never replace tracked files or existing directories.
	} else if !os.IsNotExist(err) {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(dst), 0755); err != nil {
		return err
	}
	switch {
	case info.Mode()&os.ModeSymlink != 0:
		target, err := os.Readlink(src)
		if err != nil {
			return err
		}
		return os.Symlink(target, dst)
	case info.IsDir():
		if err := os.Mkdir(dst, info.Mode().Perm()); err != nil {
			return err
		}
		entries, err := os.ReadDir(src)
		if err != nil {
			return err
		}
		for _, entry := range entries {
			if err := copyEntry(filepath.Join(src, entry.Name()), filepath.Join(dst, entry.Name()), sourceRoot, destRoot); err != nil {
				return err
			}
		}
		return nil
	case info.Mode().IsRegular():
		in, err := os.Open(src)
		if err != nil {
			return err
		}
		defer in.Close()
		out, err := os.OpenFile(dst, os.O_CREATE|os.O_EXCL|os.O_WRONLY, info.Mode().Perm())
		if err != nil {
			return err
		}
		_, err = io.Copy(out, in)
		closeErr := out.Close()
		if err != nil {
			return err
		}
		return closeErr
	default:
		return fmt.Errorf("refusing to copy a special file")
	}
}
